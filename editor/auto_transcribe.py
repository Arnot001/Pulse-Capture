"""Optional CPU Whisper worker. Inference is offline and can be cancelled by its parent."""
import json
import os
from pathlib import Path
import sys


def model_path():
    return Path(os.environ.get('PULSE_WHISPER_MODEL',
                Path(__file__).resolve().parents[1]/'.auto-models'/'base.en'))


def local_transcript(media, analysis_folder, cancel, progress):
    from .auto_analysis import atomic_json, run_local
    model = model_path()
    if not media.has_audio:
        return [], 'Silent source; no speech captions needed.'
    if not (model/'model.bin').is_file():
        return [], 'No speech model or matching .srt found. Run setup-auto.ps1 for local speech captions.'
    stamp = [(p.name, p.stat().st_size, p.stat().st_mtime_ns) for p in sorted(model.iterdir()) if p.is_file()]
    cache = Path(analysis_folder)/'transcript.json'
    identity = json.dumps([str(model.resolve()), stamp, 1])
    if cache.exists():
        cached = json.loads(cache.read_text(encoding='utf-8'))
        if cached.get('model_identity') == identity:
            return cached['cues'], 'Speech captions from cached local Whisper; review recognition accuracy.'
    progress('Transcribing speech locally on the CPU. Audio stays on this computer…')
    try:
        data = run_local([sys.executable, str(Path(__file__).resolve()), str(media.path), str(model)], cancel, 1800)
    except RuntimeError:
        # Speech recognition is optional. Keep video editing available when its
        # local decoder/model fails; cancellation is a separate exception.
        progress('Local transcription failed. Continuing without speech captions; review the output.')
        return [], ('Speech captions unavailable: local transcription failed. '
                    'Run setup-auto.ps1 and review any dialogue before publishing.')
    cues = json.loads(data)
    if len(cues) > 6000:
        raise ValueError('Too much speech for this Auto Edit job. Choose a shorter source.')
    for cue in cues:
        if not 0 <= cue['start'] < cue['end'] <= media.duration+.1 or not 0 < len(cue['text']) <= 70:
            raise ValueError('Local speech recognition returned an invalid timestamp or caption.')
        cue['end'] = min(cue['end'], media.duration)
    atomic_json(cache, {'model_identity': identity, 'cues': cues})
    return cues, ('Speech captions generated by local Whisper; review recognition accuracy.' if cues else
                  'Local Whisper detected no speech; no dialogue captions added.')


def transcribe(source, model_path):
    from faster_whisper import WhisperModel
    model = WhisperModel(str(model_path), device='cpu', compute_type='int8', local_files_only=True,
                         cpu_threads=min(8, os.cpu_count() or 2))
    segments, _ = model.transcribe(str(source), beam_size=5, vad_filter=True, word_timestamps=True,
                                   condition_on_previous_text=False)
    cues = []
    for segment in segments:
        words = segment.words or []
        group = []
        def emit():
            if group:
                text = ' '.join(w.word.strip() for w in group).strip()
                if text and group[-1].end > group[0].start:
                    cues.append({'start': round(group[0].start, 3), 'end': round(group[-1].end, 3), 'text': text})
        for word in words:
            if group and (len(' '.join(w.word.strip() for w in group+[word])) > 60 or
                          word.end-group[0].start > 4):
                emit()
                group = []
            group.append(word)
        emit()
    return cues


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    print(json.dumps(transcribe(sys.argv[1], sys.argv[2]), ensure_ascii=False))
